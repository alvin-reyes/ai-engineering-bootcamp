@pytest.fixture
def spies(agent, monkeypatch):
    """Wrap every handler in agent.HANDLERS so a test can see whether (and with what) it was called."""
    calls = {}

    def wrap(name, fn):
        def spy(**kwargs):
            calls.setdefault(name, []).append(kwargs)
            return fn(**kwargs)
        return spy

    for name, fn in list(agent.HANDLERS.items()):
        monkeypatch.setitem(agent.HANDLERS, name, wrap(name, fn))
    return calls


def tool_results(call):
    """The tool_result blocks in the last message of one recorded model call."""
    last = call["messages"][-1]
    assert last["role"] == "user" and isinstance(last["content"], list), "tool results must go back as a user message"
    return last["content"]
