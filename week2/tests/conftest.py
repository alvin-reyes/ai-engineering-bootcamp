"""Shared test helpers. Self-contained: a scripted fake client replaces the model, so no API key is needed.

The fake client has the same shape as anthropic.Anthropic() for the one call the agent makes:
    client.messages.create(model=..., system=..., tools=..., messages=...)
and returns an object with .content (text / tool_use blocks) and .stop_reason ("tool_use" or "end_turn").
Do not edit this file; the tests rely on it.
"""
import itertools
import os
import sys
from types import SimpleNamespace as NS

import pytest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

_ids = itertools.count(1)


def text(t):
    return {"type": "text", "text": t}


def tool(name, input_):
    return {"type": "tool_use", "name": name, "input": input_}


def reply(*blocks):
    stop = "tool_use" if any(b["type"] == "tool_use" for b in blocks) else "end_turn"
    return {"content": list(blocks), "stop_reason": stop}


def _block(b):
    if b["type"] == "tool_use":
        return NS(type="tool_use", id=f"toolu_test_{next(_ids):03d}", name=b["name"], input=b["input"])
    return NS(type="text", text=b["text"])


class ScriptedClient:
    """Plays the model. `script` is a list of replies (used in order) or a function (kwargs, call_no) -> reply."""

    def __init__(self, script):
        self.script = script
        self.calls = []              # one dict per create() call; "messages" is a snapshot of the history
        self.messages = self         # so client.messages.create(...) works

    def create(self, **kw):
        self.calls.append({**kw, "messages": list(kw["messages"])})
        if callable(self.script):
            spec = self.script(kw, len(self.calls))
        else:
            if len(self.calls) > len(self.script):
                raise AssertionError("the agent called the model more times than the script has replies")
            spec = self.script[len(self.calls) - 1]
        return NS(content=[_block(b) for b in spec["content"]], stop_reason=spec["stop_reason"])


class Approver:
    """A stand-in for input(): records every prompt and gives a fixed answer."""

    def __init__(self, answer):
        self.answer, self.prompts = answer, []

    def __call__(self, prompt=""):
        self.prompts.append(prompt)
        return self.answer


